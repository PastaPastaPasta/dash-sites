// Refreshes the chain checkpoints and seed nodes the extension starts from.
//   npm run build -w @dash-sites/core && node scripts/chain-checkpoint.mjs [mainnet|testnet ...]
//
// With a checkpoint already in the file, the new one is reached by verifying every header from the
// old one, so a release can only move a checkpoint along the chain the previous release trusted.
// Without one (first run), the 24 headers are taken from three nodes that must agree byte for byte.
// Seeds are evonode HTTPS endpoints from a masternode list proven at the new tip.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as chain from '../packages/core/dist/chain/index.js';

const DEPTH = 12;
const SEED_COUNT = 48;
const file = join(dirname(fileURLToPath(import.meta.url)), '..', 'packages', 'core', 'src', 'chain', 'checkpoints.ts');
const current = await import(`${file.replace(/\.ts$/, '.js').replace('/src/', '/dist/')}?${Date.now()}`).catch(() => ({ CHECKPOINTS: {}, SEEDS: {} }));
// Bootstrap nodes for a network with no seeds yet; replace with any reachable evonodes.
const BOOT = { mainnet: ['https://37.60.244.87:443', 'https://216.238.75.46:443'], testnet: ['https://85.209.243.14:1443'] };
const networks = process.argv.slice(2).length ? process.argv.slice(2) : ['mainnet', 'testnet'];
const toHex = (bytes) => Buffer.from(bytes).toString('hex');
const fromHex = (hex) => Uint8Array.from(Buffer.from(hex, 'hex'));

const checkpoints = { ...current.CHECKPOINTS };
const seeds = { ...current.SEEDS };
for (const network of networks) {
  const nodes = seeds[network]?.length ? seeds[network] : BOOT[network];
  let checkpoint = checkpoints[network];
  if (!checkpoint) {
    const answers = await Promise.allSettled(nodes.slice(0, 6).map(async (node) => ({ node, height: await chain.bestBlockHeight(node) })));
    const tips = answers.flatMap((a) => (a.status === 'fulfilled' ? [a.value] : []));
    const height = Math.min(...tips.map((t) => t.height)) - DEPTH;
    const sets = await Promise.allSettled(tips.slice(0, 3).map((t) => chain.blockHeaders(t.node, height - 23, 24)));
    const hexes = sets.flatMap((s) => (s.status === 'fulfilled' ? [s.value.map(toHex).join('')] : []));
    if (hexes.length < Math.min(3, tips.length) || new Set(hexes).size !== 1) throw new Error(`${network}: nodes disagree on the headers at ${height}`);
    const [first] = sets.filter((s) => s.status === 'fulfilled').map((s) => s.value);
    checkpoint = { network, height, headers: first.map(toHex) };
    chain.stateFromHeaders(network, height, first);
  }
  const snapshot = await chain.syncChain({ network, checkpoint, seeds: nodes, onProgress: (m) => console.error(`${network}: ${m}`) });
  // Step back DEPTH blocks from the verified tip by re-verifying the last stretch from the old checkpoint's chain.
  const tip = snapshot.chain.height;
  const target = tip - DEPTH;
  if (target > checkpoint.height) {
    let state = chain.stateFromHeaders(network, checkpoint.height, checkpoint.headers.map(fromHex));
    for (const node of snapshot.nodes.slice(0, 8)) {
      try {
        while (state.height < target) {
          const count = Math.min(2000, target - state.height);
          state = chain.extend(state, await chain.blockHeaders(node, state.height + 1, count)).state;
        }
        break;
      } catch (error) {
        console.error(`${network}: ${node}: ${error.message}`);
      }
    }
    if (state.height !== target) throw new Error(`${network}: could not verify headers to ${target}`);
    checkpoint = chain.serializeState(state);
  }
  checkpoints[network] = checkpoint;
  const pool = [...new Set(snapshot.nodes)];
  for (let i = pool.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [pool[i], pool[j]] = [pool[j], pool[i]];
  }
  seeds[network] = pool.slice(0, SEED_COUNT).sort();
  console.error(`${network}: checkpoint ${checkpoint.height}, ${seeds[network].length} seeds of ${pool.length} nodes`);
}

const order = (record) => Object.fromEntries(['mainnet', 'testnet'].filter((n) => record[n]).map((n) => [n, record[n]]));
writeFileSync(
  file,
  `// Generated by scripts/chain-checkpoint.mjs. Trust configuration: review a change like code.
import type { ChainNetwork } from './header.js';
import type { Checkpoint } from './sync.js';

/** The verified chain the extension starts from: the last 24 headers up to a recent block. */
export const CHECKPOINTS: Partial<Record<ChainNetwork, Checkpoint>> = ${JSON.stringify(order(checkpoints), null, 2)};

/** Platform nodes to ask first, by IP: evonode endpoints from a masternode list proven at the checkpoint. */
export const SEEDS: Partial<Record<ChainNetwork, string[]>> = ${JSON.stringify(order(seeds), null, 2)};
`,
);
console.error(`wrote ${file}`);

