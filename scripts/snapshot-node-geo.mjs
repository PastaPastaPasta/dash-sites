// Writes packages/shell/src/node-geo.ts: coarse (1-degree) location hints for Dash Platform
// evonodes, bundled so the browser biases its probe pool toward nearby nodes without extra
// network lookups. Rerun periodically as evonode hosting shifts.
import { writeFileSync } from 'node:fs';

const HOST = /^(\d+\.\d+\.\d+\.\d+):\d{1,5}$/;
const BATCH = 100;

async function fetchIps(network) {
  const response = await fetch(`https://quorums.${network}.networks.dash.org/masternodes`);
  if (!response.ok) throw new Error(`${network}: /masternodes returned ${response.status}`);
  const { data } = await response.json();
  const ips = new Set();
  for (const node of data ?? []) {
    const addr = node.addresses?.platform_https?.[0];
    const match = typeof addr === 'string' ? HOST.exec(addr) : null;
    if (match) ips.add(match[1]);
  }
  return [...ips].sort();
}

async function geolocate(ips) {
  const coords = new Map();
  for (let i = 0; i < ips.length; i += BATCH) {
    const slice = ips.slice(i, i + BATCH);
    const response = await fetch('http://ip-api.com/batch?fields=query,status,lat,lon', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(slice),
    });
    if (!response.ok) throw new Error(`ip-api returned ${response.status}`);
    const results = await response.json();
    for (const entry of results) {
      if (entry.status === 'success' && typeof entry.lat === 'number' && typeof entry.lon === 'number') {
        coords.set(entry.query, [Math.round(entry.lat), Math.round(entry.lon)]);
      }
    }
    if (i + BATCH < ips.length) await new Promise((r) => setTimeout(r, 1500));
  }
  return coords;
}

function compact(coords) {
  const byPrefix = new Map();
  for (const [ip, pt] of coords) {
    const p16 = ip.split('.').slice(0, 2).join('.');
    const list = byPrefix.get(p16) ?? [];
    list.push([ip, pt]);
    byPrefix.set(p16, list);
  }
  const p16 = {};
  const ip = {};
  for (const prefix of [...byPrefix.keys()].sort()) {
    const entries = byPrefix.get(prefix);
    const counts = new Map();
    for (const [, pt] of entries) {
      const k = `${pt[0]},${pt[1]}`;
      counts.set(k, (counts.get(k) ?? 0) + 1);
    }
    const [bestKey] = [...counts.entries()].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))[0];
    const bestPt = bestKey.split(',').map(Number);
    p16[prefix] = bestPt;
    for (const [addr, pt] of entries.sort((a, b) => a[0].localeCompare(b[0]))) {
      if (pt[0] !== bestPt[0] || pt[1] !== bestPt[1]) ip[addr] = pt;
    }
  }
  return { p16, ip };
}

const out = {};
for (const network of ['testnet', 'mainnet']) {
  const ips = await fetchIps(network);
  const coords = await geolocate(ips);
  out[network] = compact(coords);
  console.log(network, { totalIps: ips.length, resolved: coords.size, p16: Object.keys(out[network].p16).length, overrides: Object.keys(out[network].ip).length });
}

const file = new URL('../packages/shell/src/node-geo.ts', import.meta.url);
writeFileSync(
  file,
  `// Generated by scripts/snapshot-node-geo.mjs. Coarse 1-degree coordinates for probe geo-biasing.
import type { Network } from '@dash-sites/core';
import type { NodeGeo } from './geo.js';

declare const __ONLY_NETWORK__: Network | undefined;

export const NODE_GEO: Partial<Record<Network, NodeGeo>> = {
${Object.entries(out)
  .map(
    ([network, geo]) =>
      `  ...((typeof __ONLY_NETWORK__ === 'undefined' || __ONLY_NETWORK__ === '${network}') && {\n    ${JSON.stringify(network)}: ${JSON.stringify(geo)},\n  }),`,
  )
  .join('\n')}
};
`,
);
